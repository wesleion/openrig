import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
const home='/home/weslei';
const repo=path.dirname(new URL(import.meta.url).pathname);
const installed=home+'/.nvm/versions/node/v24.16.0/lib/node_modules/@openrig/cli';
const backup=home+'/.openrig/maintenance/20261008-jev-telemetry-backup';
if(fs.existsSync(backup)) throw Error('Backup already exists; refusing to replace it.');
fs.mkdirSync(backup,{recursive:true,mode:0o700});
const require=createRequire(repo+'/packages/daemon/package.json');
const Database=require('better-sqlite3');
const db=new Database(home+'/.openrig/openrig.sqlite',{readonly:true});
await db.backup(backup+'/openrig.sqlite'); db.close();
for(const dir of ['dist','daemon','ui','tui']) if(fs.existsSync(installed+'/'+dir)) fs.cpSync(installed+'/'+dir,backup+'/runtime/'+dir,{recursive:true});
for(const file of ['daemon.json','config.json']) fs.copyFileSync(home+'/.openrig/'+file,backup+'/'+file);
fs.copyFileSync(home+'/workspaces/openrig-lab/rig.yaml',backup+'/lab-rig.yaml');
const controller=home+'/workspaces/openrig-lab/ferramentas/jev-controller';
for(const dir of ['src','test','.state','state','dist']) if(fs.existsSync(controller+'/'+dir)) fs.cpSync(controller+'/'+dir,backup+'/jev/'+dir,{recursive:true});
const panes=execFileSync('tmux',['list-panes','-a','-F','#{session_name}\t#{pane_id}\t#{pane_pid}\t#{pane_current_command}'],{encoding:'utf8'});
fs.writeFileSync(backup+'/panes-before.tsv',panes,{mode:0o600});
const processes=execFileSync('ps',['-eo','pid,ppid,lstart,args'],{encoding:'utf8',env:{...process.env,LC_ALL:'C'}}).split('\n').filter(x=>/claude|codex|openrig.*daemon|daemon\/dist\/index/.test(x));
fs.writeFileSync(backup+'/processes-before.txt',processes.join('\n'),{mode:0o600});
fs.writeFileSync(backup+'/source-head.txt',execFileSync('git',['rev-parse','HEAD'],{cwd:repo,encoding:'utf8'}));
fs.writeFileSync(backup+'/source-changes.patch',execFileSync('git',['diff','--binary'],{cwd:repo,maxBuffer:20000000}));
console.log(JSON.stringify({backup,panes:panes.trim().split('\n').length,runtimeSaved:true,databaseSaved:true}));
